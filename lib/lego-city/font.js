export const GLYPH_W = 3;
export const GLYPH_H = 5;
export const GLYPH_GAP = 1;

export function glyph(ch) {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "];
}

/** Width in cells of a rendered string (no trailing gap). */
export function textWidth(text) {
  return text.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP;
}

/**
 * Yields [col, row] cells (row 0 = top) that should hold a brick.
 */
export function* textCells(text) {
  for (let i = 0; i < text.length; i++) {
    const rows = glyph(text[i]);
    const ox = i * (GLYPH_W + GLYPH_GAP);
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (rows[r][c] === "#") yield [ox + c, r];
      }
    }
  }
}

