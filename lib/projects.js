export function getProjectByTitle(title) {
  return projects.find((p) => p.title === title);
}

export function filterProjects(activeFilter) {
  if (activeFilter === "recent") {
    return [...projects].sort((a, b) => parseInt(b.year) - parseInt(a.year));
  }
  if (activeFilter === "all") {
    return projects;
  }
  return projects.filter((p) => p.category === activeFilter);
}
